/**
 * Фразы индикатора загрузки.
 *
 * Это **сценарий**, а не мешок реплик: порядок значим. Первые фразы объясняют,
 * что происходит, последние — успокаивают, если ответ задерживается. Ротатор
 * идёт по списку сверху вниз и дальше крутит только хвост (`TAIL_SIZE`), чтобы
 * после «Почти готово…» не выпало снова «Думаю…» — это читалось бы как откат.
 *
 * Ни одна фраза не называет предметных сущностей (договор, тариф, объём,
 * стоимость): набор крутится независимо от того, что спросили, и такая фраза
 * начала бы врать. «Ищу по Трансфере» и «анализирую данные» — формулировки
 * заказчика из постановки «Доработки 2», пункт 7: они верны для любого вопроса.
 */
export const LOADING_PHRASES = [
  'Думаю…',
  'Ищу по Трансфере…',
  'Анализирую данные…',
  'Сверяюсь с цифрами…',
  'Раскладываю по полочкам…',
  'Собираю картинку…',
  'Ещё чуть-чуть…',
  'Почти готово…',
];

/** Сколько последних фраз крутятся по кругу, когда сценарий доигран. */
export const TAIL_SIZE = 2;

/**
 * Пауза между фразами. Прежние 1800 мс заказчик забраковал как мельтешение
 * («Доработки 3», пункт 5: увеличить интервал в полтора раза). 2700 мс — за
 * шестисекундное ожидание сменяются три фразы: сценарий успевает начаться, но
 * подпись не дёргается.
 */
export const PHRASE_INTERVAL_MS = 2700;

export default LOADING_PHRASES;
